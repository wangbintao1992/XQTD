#!/usr/bin/env python3
"""把 assets/scripts/PathGraphData.ts 转成 godot/scripts/data/path_graph_data.gd。

转换时把每条边的首/尾点吸附到 a/b 节点坐标 —— 原数据里边 3→2 的起点离节点 3
有 138 设计单位，直接搬会让敌人到站瞬间「瞬移」。

用法：
    python3 godot/tools/convert_path_graph.py
"""

from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "assets" / "scripts" / "PathGraphData.ts"
DST = ROOT / "godot" / "scripts" / "data" / "path_graph_data.gd"


def block(text: str, name: str) -> str:
    m = re.search(rf"export const {name}[^=]*=\s*\[(.*?)\];", text, re.S)
    if not m:
        raise SystemExit(f"cannot find {name} in {SRC}")
    return m.group(1)


def parse_nodes(s: str):
    out = []
    for m in re.finditer(r"\{\s*x:\s*(-?\d+(?:\.\d+)?),\s*y:\s*(-?\d+(?:\.\d+)?)\s*\}", s):
        out.append((float(m.group(1)), float(m.group(2))))
    return out


def parse_edges(s: str):
    out = []
    for m in re.finditer(
        r"\{\s*a:\s*(\d+),\s*b:\s*(\d+),.*?points:\s*\[([^\]]*)\]\s*\}",
        s,
        re.S,
    ):
        a = int(m.group(1))
        b = int(m.group(2))
        nums = [float(x) for x in re.findall(r"-?\d+(?:\.\d+)?", m.group(3))]
        pts = [(nums[i], nums[i + 1]) for i in range(0, len(nums) - 1, 2)]
        out.append({"a": a, "b": b, "points": pts})
    return out


def fmt(v: float) -> str:
    if v == int(v):
        return str(int(v))
    return f"{v:.3f}".rstrip("0").rstrip(".")


def main() -> None:
    text = SRC.read_text(encoding="utf-8")
    nodes = parse_nodes(block(text, "PATH_GRAPH_NODES"))
    edges = parse_edges(block(text, "PATH_GRAPH_EDGES"))
    if not nodes or not edges:
        raise SystemExit("empty parse — check PathGraphData.ts format")

    for e in edges:
        if not e["points"]:
            raise SystemExit(f"edge {e['a']}-{e['b']} has no points")
        # 吸附端点，消除提取误差导致的走位瞬移
        e["points"][0] = nodes[e["a"]]
        e["points"][-1] = nodes[e["b"]]

    lines = [
        "# AUTO-GENERATED by godot/tools/convert_path_graph.py — do not edit by hand.",
        "# Source: assets/scripts/PathGraphData.ts",
        "# Design space: 1280x720, origin at the Canvas centre, y up.",
        "",
        "const NODES := [",
    ]
    for x, y in nodes:
        lines.append(f"\tVector2({fmt(x)}, {fmt(y)}),")
    lines.append("]")
    lines.append("")
    lines.append("const EDGES := [")
    for e in edges:
        pts = ", ".join(f"Vector2({fmt(x)}, {fmt(y)})" for x, y in e["points"])
        lines.append(f'\t{{"a": {e["a"]}, "b": {e["b"]}, "points": [{pts}]}},')
    lines.append("]")
    lines.append("")

    DST.parent.mkdir(parents=True, exist_ok=True)
    DST.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {DST} ({len(nodes)} nodes, {len(edges)} edges)")


if __name__ == "__main__":
    main()
